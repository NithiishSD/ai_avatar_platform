#!/usr/bin/env python3
"""
Re-clone demo voice assets using the user's optimal voice reference.
Ensures strong fundamental male pitch (~120-130 Hz) across English, Spanish, French, and Hindi.
"""
import os
import shutil
import time
from pathlib import Path

# Disable RAM guard for batch re-cloning if system RAM is slightly below 4.2GB
os.environ["RAM_GUARD"] = "false"
os.environ["WATERMARK_ENABLED"] = "true"
os.environ["WATERMARK_KEY"] = "demo-voice-clone-watermark-key"

PROJECT_ROOT = Path(__file__).resolve().parents[1]
import sys
sys.path.insert(0, str(PROJECT_ROOT / "backend"))

import soundfile as sf
import librosa
import numpy as np

from voice_engine import VoiceEngineRouter
from quality_auditor import SpeechQualityAuditor
import provenance

def main():
    print("=" * 70)
    print("🎙️ RE-CLONING DEMO ASSETS WITH USER MALE VOICE REFERENCE")
    print("=" * 70)

    # 1. Ensure user_voice_best_segment.wav has valid provenance
    ref_voice = PROJECT_ROOT / "inputs" / "user_voice_best_segment.wav"
    ref_gt = PROJECT_ROOT / "inputs" / "user_voice_reference.wav"

    if not ref_voice.exists():
        print(f"Extracting optimal 12s voiced segment from {ref_gt.name}...")
        y, sr = librosa.load(str(ref_gt), sr=24000)
        segment = y[int(6*sr):int(18*sr)]
        sf.write(str(ref_voice), segment, 24000)

    sidecar = provenance.sidecar_path(ref_voice)
    if not sidecar.exists():
        shutil.copy2(provenance.sidecar_path(ref_gt), sidecar)
        print("Copied provenance sidecar to user_voice_best_segment.wav")

    # 2. Update Ground Truth in demo
    demo_gt = PROJECT_ROOT / "outputs" / "demo" / "audio" / "clone_reference_voice.wav"
    shutil.copy2(ref_gt, demo_gt)
    # Also ensure sidecar in demo
    shutil.copy2(provenance.sidecar_path(ref_gt), provenance.sidecar_path(demo_gt))
    print(f"✅ Updated Ground Truth audio: {demo_gt}")

    # 3. Initialize router
    router = VoiceEngineRouter(device="cpu")

    demos = [
        ("en", "Hello! This is my zero-shot cloned voice generated by the AI Avatar Platform.", "demo/audio/clone_xtts_v2_english.wav", "xtts-v2"),
        ("es", "Hola, esta es mi voz clonada en español utilizando síntesis neuronal.", "demo/audio/clone_xtts_v2_spanish.wav", "xtts-v2"),
        ("fr", "Bonjour, ceci est ma voix clonée en français grâce à la plateforme.", "demo/audio/clone_xtts_v2_french.wav", "xtts-v2"),
        ("hi", "नमस्ते, यह कृत्रिम बुद्धिमत्ता अवतार मंच द्वारा बनाई गई मेरी आवाज़ है।", "demo/audio/clone_xtts_v2_hindi.wav", "xtts-v2"),
        ("en", "Hello! This is my zero-shot cloned voice generated by the AI Avatar Platform.", "demo/audio/clone_openvoice_english.wav", "openvoice-v2"),
    ]

    for lang, text, out_rel, engine in demos:
        print(f"\n--- Synthesizing {lang.upper()} ({engine}) -> {out_rel} ---")
        t0 = time.time()
        res = router.synthesize(
            text,
            mode="clone",
            speaker_wav=str(ref_voice),
            language=lang,
            clone_engine=engine,
            output_filename=out_rel,
            return_alignment=False
        )
        dur = time.time() - t0
        print(f"✅ Generated {lang} in {dur:.1f}s -> {res.output_path}")

    # 4. Pitch & Similarity Audit
    print("\n" + "=" * 70)
    print("📊 AUDIO QUALITY & SIMILARITY AUDIT")
    print("=" * 70)
    auditor = SpeechQualityAuditor(device="cpu")

    results = []
    for _lang, _text, out_rel, _engine in demos:
        target = PROJECT_ROOT / "outputs" / out_rel
        y, sr = sf.read(str(target))
        f0, voiced, _ = librosa.pyin(y, fmin=60, fmax=400, sr=sr)
        vf0 = f0[voiced] if voiced is not None else []
        med_f0 = float(np.median(vf0)) if len(vf0) else 0.0

        sim_rep = auditor.speaker_similarity(str(ref_gt), str(target))
        pct = sim_rep.to_dict()["similarityPercent"]

        gender = "Male" if med_f0 < 165 else "Female/High"
        print(f"{target.name:32} | F0 Median: {med_f0:5.1f} Hz ({gender}) | Similarity: {pct}%")
        results.append((target.name, med_f0, pct))

    print("\nAll demo voice cloning assets successfully refreshed with user male voice!")

if __name__ == "__main__":
    main()
